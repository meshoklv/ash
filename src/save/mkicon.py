#!/usr/bin/env python3
"""Draw the save icon (ICON0.PNG 144x80, our own art: no game assets) and write it as a C array.

    tools/.venv/bin/python src/save/mkicon.py
-> src/save/icon0.png (to look at), src/save/icon0.h (const unsigned char ash_icon0_png[])
"""
import io
import math
import pathlib

from PIL import Image, ImageDraw, ImageFont

here = pathlib.Path(__file__).resolve().parent


def font(size):
    for p in ("/usr/share/fonts/truetype/dejavu/DejaVuSerif-Bold.ttf",
              "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf",
              "/usr/share/fonts/dejavu/DejaVuSans-Bold.ttf"):
        if pathlib.Path(p).exists():
            return ImageFont.truetype(p, size)
    return ImageFont.load_default()


W, H = 144, 80
im = Image.new("RGB", (W, H))
px = im.load()
for y in range(H):
    for x in range(W):
        # dark stone with a warm glow from the bottom left (a bonfire)
        d = math.hypot((x - 34) / 70, (y - 70) / 55)
        g = max(0.0, 1.0 - d)
        px[x, y] = (int(14 + 150 * g * g), int(12 + 70 * g * g), int(12 + 18 * g))
d = ImageDraw.Draw(im)
# a coiled sword stuck in a little ember pile
d.polygon([(22, 66), (34, 52), (46, 66)], fill=(60, 25, 10))
for i, (r, c) in enumerate([(9, (255, 120, 20)), (6, (255, 180, 60)), (3, (255, 240, 170))]):
    d.ellipse([34 - r, 60 - r * 1.6, 34 + r, 62], fill=c)
d.line([(34, 18), (34, 60)], fill=(200, 200, 210), width=3)
d.line([(28, 26), (40, 26)], fill=(160, 140, 110), width=3)
for k in range(5):   # the coil
    y = 34 + k * 5
    d.arc([29, y - 2, 39, y + 3], 200, 340, fill=(90, 80, 70), width=2)
f1, f2 = font(28), font(13)
d.text((60, 12), "ASH", font=f1, fill=(255, 214, 150), stroke_width=1, stroke_fill=(40, 15, 5))
d.text((62, 50), "DS1  PSP", font=f2, fill=(220, 220, 220))
d.rectangle([0, 0, W - 1, H - 1], outline=(150, 90, 40), width=1)

buf = io.BytesIO()
im.save(buf, "PNG", optimize=True)
data = buf.getvalue()
(here / "icon0.png").write_bytes(data)
lines = ["/* ICON0.PNG 144x80 for the save data (generated by src/save/mkicon.py - do not edit) */",
         "#ifndef ASH_ICON0_H", "#define ASH_ICON0_H", "",
         f"static const unsigned char ash_icon0_png[{len(data)}] __attribute__((aligned(16))) = {{"]
for i in range(0, len(data), 20):
    lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 20]) + ",")
lines += ["};", "", "#endif", ""]
(here / "icon0.h").write_text("\n".join(lines))
print(f"icon0.png {len(data)} B, icon0.h")
