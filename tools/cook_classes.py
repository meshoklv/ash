#!/usr/bin/env python3
"""Cook the character-creation preview models: every DS1 starting class in its starting armour + weapon + shield,
both genders, plus a few face/hair presets for bare-headed classes, and one idle clip.

    tools/.venv/bin/python tools/cook_classes.py --out-dir ~/ash-assets/cooked/menu [--budget 2200] [--only 3001]

Everything comes from the game data (nothing typed by hand):
  * CharaInitParam rows 3000..3009 (the 10 classes) -> HeadArmor/BodyArmor/HandsArmor/LegsArmor (EquipParamProtector
    .EquipmentModel) and RightHandWeapon1 / LeftHandWeapon1 (EquipParamWeapon.WeaponModel).
  * part file = parts/<HD|BD|AM|LG>_<A|M|F>_<model:04d>.partsbnd.dcx (A = unisex, tried first), weapons WP_A_<model>.
    EquipmentModel 0 = bare (the *_0000 naked parts, skin textures from parts/Common_Body.tpf).
  * face/hair presets (src/menu, "Внешность"): FC_<g>_0000 + HR_<g>_<model> of EquipParamProtector hair rows
    (ArmorType 4: male 1000..1900, female 3000..3900). Which 4 rows we offer is our choice [придумал].
  * skeleton, weights, chunking, .ashc/.ashanim writers: tools/cook_knight.py (imported as a library).

Outputs (outside git, FromSoftware data):
  cls_<row>_<m|f>.ashc   body: armour + R weapon on R_Weapon + shield on L_Weapon (one per class and gender)
  head_<m|f>_<k>.ashc    face + hair preset k (drawn with the same skin matrices when the class has no helmet)
  menu_idle.ashanim      clip "idle" (a00_0000) only, same 30-bone skeleton
  classes.json           stats per file (tris, bytes, parts, missing textures)
"""
from __future__ import annotations

import argparse
import json
import logging
import sys
import time
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).parent))
logging.disable(logging.WARNING)
import cook_knight as ck  # noqa: E402
from ashm import BF_ALPHA, BF_NOCULL, Batch, simplify, weld  # noqa: E402
from cook_scene import TexBank  # noqa: E402
from PIL import Image  # noqa: E402
from dsrlib import DSR, Binder, binder_flver, binder_textures, dds_to_image, mesh_arrays, mesh_textures, \
    mesh_triangles, valid_meshes  # noqa: E402

CLASS_ROWS = list(range(3000, 3010))
# hair presets per gender: EquipParamProtector rows (names = item FMG 12). [придумал: which 4 of 10]
HAIR_PRESETS = {"M": [1000, 1200, 1100, 1900], "F": [3100, 3300, 3500, 3900]}
# hair diffuse in DSR is grey (~105/255), the colour comes from the shader (hair colour of the character): we bake
# one colour per preset as an RGB multiplier [придумал: по названиям цветов FMG 135070.. «Черный/Каштановый/Русый»]
HAIR_TINT = {"M": [(0.57, 0.40, 0.29), (0.57, 0.40, 0.29), (0.90, 0.57, 0.33), (0.33, 0.30, 0.29)],
             "F": [(0.90, 0.57, 0.33), (1.33, 1.10, 0.76), (0.33, 0.30, 0.29), (1.14, 0.52, 0.33)]}
# share of the triangle budget per part category
SHARE = {"HD": 0.16, "BD": 0.34, "AM": 0.17, "LG": 0.2, "WR": 0.07, "WL": 0.06, "FC": 0.45, "HR": 0.55}


def load_params():
    from soulstruct.darksouls1r.params.gameparambnd import GameParamBND
    g = GameParamBND.from_path(DSR / "param/GameParam/GameParam.parambnd.dcx")
    return {k.rsplit("\\", 1)[1]: v.rows for k, v in g.params.items()}


_COMMON: dict = {}


def common_tex(stem: str):
    """Skin textures (bd_m_body, fc_m_face ...) live in parts/Common_Body*.tpf, not in the part binders.
    fg_face_gen (the FaceGen face front, FG_A_0000) is generated by the game at run time: we use a flat skin colour
    = median of FC_<g>_face (no facial features - "без facegen")."""
    if stem.lower().startswith("fg_face_gen"):
        src = common_tex("fc_f_face" if stem.lower().endswith("_f") else "fc_m_face")
        a = np.asarray(src)[:, :, :3].reshape(-1, 3)
        c = tuple(int(x) for x in np.median(a, axis=0)) + (255,)
        return Image.new("RGBA", (8, 8), c)
    if not _COMMON:
        from soulstruct.containers import TPF
        for f in ("Common_Body.tpf", "Common_Body_M.tpf"):
            for t in TPF.from_path(DSR / "parts" / f).textures:
                _COMMON.setdefault(t.stem.lower(), t.data)
    d = _COMMON.get(stem.lower())
    return dds_to_image(d) if d is not None else None


def gender_of(parts) -> str:
    return "F" if any("_F_" in p[0] for p in parts) else "M"


def part_file(prefix: str, gender: str, model: int) -> str | None:
    for g in ("A", gender):
        name = f"{prefix}_{g}_{model:04d}"
        if (DSR / "parts" / f"{name}.partsbnd.dcx").exists():
            return name
    return None


def cook_parts(sk, bank: TexBank, parts: list, budget: int, stats: dict) -> list[Batch]:
    """cook_knight.cook_mesh with an explicit part list [(file, share, attach bone or None)] and the
    Common_Body texture fallback."""
    K = len(sk.keep)
    out, src, missing = [], 0, []
    for part, share, attach, *rest in parts:
        tint = rest[0] if rest else None
        b = Binder.from_path(DSR / "parts" / f"{part}.partsbnd.dcx")
        pf = binder_flver(b)
        tx = binder_textures(b)
        p2k = ck.part_bone_to_kept(sk, pf)
        pb = []
        for m in valid_meshes(pf):
            dstem = (mesh_textures(m).get("g_Diffuse") or "").lower()
            if not dstem:
                continue
            if dstem == "fg_eye":
                continue
            if dstem == "fg_face_gen" and part.startswith("FG_") and gender_of(parts) == "F":
                dstem = "fg_face_gen_f"
            if dstem not in tx:
                im = common_tex(dstem)
                if im is None:
                    missing.append(f"{part}:{dstem}")
                    continue
                tx[dstem] = (im, "common")
            d = mesh_arrays(m)
            tri = mesh_triangles(m)
            if len(tri) == 0:
                continue
            src += len(tri)
            pos = d["pos"].astype(np.float64)
            nrm = d.get("normal", np.tile([0, 1, 0], (len(pos), 1)))[:, :3].astype(np.float64)
            W = np.zeros((len(pos), K), np.float32)
            if not m.is_dynamic:
                bi = m.default_bone_index if m.default_bone_index >= 0 else 0
                bt = pf.get_bone_tree().get_bone_armature_space_transforms()[bi]
                Rb = np.array(bt[1].data); tb = np.array(list(bt[0]))
                pos = pos @ Rb.T + tb; nrm = nrm @ Rb.T
                if attach:
                    A = sk.bind[sk.idx[attach]]
                    pos = pos @ A[:3, :3].T + A[:3, 3]; nrm = nrm @ A[:3, :3].T
                    W[:, sk.kidx[attach]] = 1
                else:
                    W[:, p2k[bi]] = 1
            else:
                bi = d["bone_indices"]
                bw = d.get("bone_weights")
                if bw is None:
                    bw = np.zeros(bi.shape, np.float32); bw[:, 0] = 1
                lut = np.array(m.bone_indices) if len(m.bone_indices) else None
                for kk in range(bi.shape[1]):
                    idx = bi[:, kk]
                    g = lut[np.clip(idx, 0, len(lut) - 1)] if lut is not None else idx
                    kb = np.array(p2k)[np.clip(g, 0, len(p2k) - 1)]
                    np.add.at(W, (np.arange(len(pos)), kb), bw[:, kk])
                W[W.sum(1) < 1e-6, 0] = 1
            pos[:, 0] *= -1; nrm[:, 0] *= -1
            if tint:
                def load(s=dstem, t=tint):
                    a = np.asarray(tx[s][0]).astype(np.float32)
                    a[:, :, :3] = np.clip(a[:, :, :3] * np.array(t, np.float32), 0, 255)
                    return Image.fromarray(a.astype(np.uint8), "RGBA")
            else:
                def load(s=dstem):
                    return tx[s][0]
            ti = bank.add(("p", dstem, tint), load, 128)
            flags = BF_ALPHA | BF_NOCULL if bank.items[ti].alpha else 0
            pb.append(Batch(ti, pos.astype(np.float32), d["uv0"].astype(np.float32), nrm.astype(np.float32), tri,
                            flags, f"{part}:{dstem}", W))
        total = sum(p.ntri for p in pb)
        ratio = min(1.0, budget * share / max(1, total))
        for p in pb:
            s = simplify(weld(p), max(8, int(p.ntri * ratio)))
            s = ck.unify_corners(s)
            s.col = (s.col / (np.linalg.norm(s.col, axis=1, keepdims=True) + 1e-9)).astype(np.float32)
            out.append(s)
    stats.update(src_tris=src, tris=sum(b.ntri for b in out), missing_tex=missing)
    return out


def write_model(path: Path, sk, parts: list, budget: int) -> dict:
    st: dict = dict(parts=[p[0] for p in parts])
    bank = TexBank(128)
    batches = cook_parts(sk, bank, parts, budget, st)
    chunks = []
    for b in batches:
        Wq = ck.quantize_weights(b.attr)
        for pal, used, tri, w in ck.chunk_batch(b, Wq):
            chunks.append((b.tex, b.flags, pal, b.pos[used], b.uv[used], b.col[used], w, tri))
    st.update(ck.write_ashc(path, sk, bank, chunks))
    st["weights_ok"] = all((c[6].astype(int).sum(1) == 128).all() for c in chunks)
    return st


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out-dir", required=True)
    ap.add_argument("--budget", type=int, default=1800, help="body triangle budget per class")
    ap.add_argument("--head-budget", type=int, default=700)
    ap.add_argument("--only", type=int, help="one CharaInitParam row (test)")
    ap.add_argument("--genders", default="MF")
    a = ap.parse_args()
    out = Path(a.out_dir).expanduser()
    out.mkdir(parents=True, exist_ok=True)
    t0 = time.time()
    P = load_params()
    ci, pr, wp = P["CharaInitParam"], P["EquipParamProtector"], P["EquipParamWeapon"]
    sk = ck.Skeleton(ck.KEEP)
    report: dict = dict(classes={}, heads={})
    # ---- idle clip
    hsk = ck.load_hkx_skeleton()
    c = ck.cook_clip(sk, hsk, "a00_0000")
    report["anim"] = ck.write_ashanim(out / "menu_idle.ashanim", len(sk.keep),
                                      [("idle", ck.anim_id("a00_0000"), True, c, ck.quantize_clip(c))])
    print("menu_idle.ashanim", report["anim"], flush=True)
    rows = [a.only] if a.only else CLASS_ROWS
    for row in rows:
        r = ci[row]
        for g in a.genders:
            parts = []
            for pre, fld in (("HD", "HeadArmor"), ("BD", "BodyArmor"), ("AM", "HandsArmor"), ("LG", "LegsArmor")):
                model = pr[getattr(r, fld)].EquipmentModel
                f = part_file(pre, g, model)
                if f:
                    parts.append((f, SHARE[pre], None))
                else:
                    print(f"  ! {row} {g}: no part {pre} model {model}")
            for fld, att, key in (("RightHandWeapon1", "R_Weapon", "WR"), ("LeftHandWeapon1", "L_Weapon", "WL")):
                wid = getattr(r, fld)
                if wid > 0:
                    f = f"WP_A_{wp[wid].WeaponModel:04d}"
                    if (DSR / "parts" / f"{f}.partsbnd.dcx").exists():
                        parts.append((f, SHARE[key], att))
            name = f"cls_{row}_{g.lower()}.ashc"
            st = write_model(out / name, sk, parts, a.budget)
            st["bare_head"] = pr[r.HeadArmor].EquipmentModel == 0
            report["classes"][name] = st
            print(f"{name}: {st['tris']} tris, {st['bytes']} B, tex {st['tex']}, parts {st['parts']}"
                  f"{' MISSING ' + str(st['missing_tex']) if st['missing_tex'] else ''}", flush=True)
    if not a.only:
        for g in a.genders:
            for k, hrow in enumerate(HAIR_PRESETS[g]):
                parts = [(f"FC_{g}_0000", SHARE["FC"] * 0.6, None), ("FG_A_0000", SHARE["FC"] * 0.4, None)]
                hm = pr[hrow].EquipmentModel
                hf = part_file("HR", g, hm)
                if hf:
                    parts.append((hf, SHARE["HR"], None, HAIR_TINT[g][k]))
                name = f"head_{g.lower()}_{k}.ashc"
                st = write_model(out / name, sk, parts, a.head_budget)
                st["hair_row"] = hrow
                report["heads"][name] = st
                print(f"{name}: {st['tris']} tris, {st['bytes']} B, parts {st['parts']}", flush=True)
    report["cook_seconds"] = round(time.time() - t0, 1)
    (out / ("classes.json" if not a.only else f"classes_{a.only}.json")).write_text(
        json.dumps(report, indent=1, default=str))
    bad = [n for n, s in {**report["classes"], **report["heads"]}.items() if not s["weights_ok"]]
    print("done in", report["cook_seconds"], "s;", "weights OK" if not bad else f"BAD WEIGHTS {bad}")


if __name__ == "__main__":
    main()
