#!/usr/bin/env python3
"""Probe DSR source assets for the first Ash scene (Undead Asylum m18_01) and write the stats design notes.

    tools/.venv/bin/python tools/probe.py [--out the stats design notes]

All numbers come from parsing the real files (LOD0 face set, triangle strips unwound, degenerates dropped).
"""
from __future__ import annotations

import argparse
import sys
import time
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from dsrlib import DSR, Binder, FLVER, binder_flver, binder_textures, chr_textures, load_map_texture, mesh_textures, mesh_triangles, valid_meshes  # noqa: E402
from soulstruct.darksouls1r.maps.msb import MSB  # noqa: E402

MAP = "m18_01_00_00"
AREA = "m18"
CHARS = ["c0000", "c2230", "c2500", "c1000"]
PARTS = ["HD_A_9500", "BD_A_9500", "AM_A_9500", "LG_M_9500", "WP_A_0201", "WP_A_1516"]


def flver_stats(f: FLVER) -> dict:
    tris = verts = 0
    mats = set()
    bad = len(f.meshes) - len(valid_meshes(f))
    for m in valid_meshes(f):
        tris += len(mesh_triangles(m))
        verts += len(m.vertices)
        mats.add((m.material.name, m.material.mat_def_path.rsplit("\\", 1)[-1]))
    return dict(meshes=len(f.meshes) if not bad else f"{len(f.meshes)} ({bad} undecodable)", tris=tris, verts=verts, bones=len(f.bones), mats=len(mats))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(Path(__file__).parent.parent / "the stats design notes"))
    ap.add_argument("--cooked", default=str(Path.home() / "ash-assets/cooked/hall.json"),
                    help="cook stats JSON to summarise (written by cook_scene.py next to the .ashm)")
    args = ap.parse_args()
    t0 = time.time()
    L = []
    L.append(f"# Ash — source asset stats (DSR, {MAP})\n")
    L.append(f"_Generated by `tools/probe.py` from the real files ({time.strftime('%Y-%m-%d')}). "
             "Triangles = LOD0 face set, strips unwound, degenerates dropped._\n")

    msb = MSB.from_path(DSR / "map/MapStudio" / f"{MAP}.msb")
    L.append("## MSB\n")
    L.append(f"- map pieces: {len(msb.map_pieces)} (models: {len(msb.map_piece_models)}), all placed at "
             f"{sorted({tuple(round(float(x), 1) for x in p.translate) for p in msb.map_pieces})}")
    L.append(f"- characters: {len(msb.characters)}, objects: {len(msb.objects)}, collisions: {len(msb.collisions)}")
    for p in msb.player_starts:
        L.append(f"- player start {p.name}: pos {[round(float(x), 2) for x in p.translate]}, rot {[round(float(x), 1) for x in p.rotate]}")
    counts: dict[str, list] = {}
    for c in msb.characters:
        counts.setdefault(c.model.name, []).append(c)
    L.append("\n| model | count | example pos | example entity |\n|---|---|---|---|")
    for k, v in sorted(counts.items()):
        L.append(f"| {k} | {len(v)} | {[round(float(x), 1) for x in v[0].translate]} | {v[0].entity_id} |")
    L.append("\n(c2230 = Asylum Demon, c2232 = Stray Demon, c0000 = human/player model; others per ChrDB.)\n")

    # ---- map pieces
    L.append("## Map pieces (m18_01)\n")
    L.append("| piece | meshes | tris | verts | bones | materials | diffuse textures |\n|---|---|---|---|---|---|---|")
    tot = dict(tris=0, verts=0)
    tex_dims: dict[str, str] = {}
    for model in msb.map_piece_models:
        path = DSR / "map" / MAP / f"{model.name}A18.flver.dcx"
        f = FLVER.from_path(path)
        s = flver_stats(f)
        tot["tris"] += s["tris"]; tot["verts"] += s["verts"]
        diffuse = set()
        for m in valid_meshes(f):
            mt = mesh_textures(m)
            for slot, stem in mt.items():
                if stem and stem not in tex_dims and slot in ("g_Diffuse", "g_Lightmap"):
                    r = load_map_texture(AREA, stem)
                    tex_dims[stem] = f"{r[0].size[0]}x{r[0].size[1]} {r[1]}" if r else "MISSING"
            if mt.get("g_Diffuse"):
                diffuse.add(mt["g_Diffuse"])
        L.append(f"| {model.name} | {s['meshes']} | {s['tris']} | {s['verts']} | {s['bones']} | {s['mats']} | {len(diffuse)} |")
    L.append(f"| **total** | | **{tot['tris']}** | **{tot['verts']}** | | | |\n")
    sizes: dict[str, int] = {}
    for v in tex_dims.values():
        sizes[v] = sizes.get(v, 0) + 1
    L.append(f"Map textures referenced (diffuse + lightmap): {len(tex_dims)} unique.\n")
    L.append("| size / format | count |\n|---|---|")
    for k, v in sorted(sizes.items(), key=lambda kv: -kv[1]):
        L.append(f"| {k} | {v} |")

    # ---- characters
    L.append("\n## Characters (chrbnd)\n")
    L.append("| chr | meshes | tris | verts | bones | materials | textures |\n|---|---|---|---|---|---|---|")
    for c in CHARS:
        b = Binder.from_path(DSR / "chr" / f"{c}.chrbnd.dcx")
        f = binder_flver(b)
        s = flver_stats(f)
        tx = chr_textures(c)
        if c == "c2230":
            tx.update(chr_textures("c2239"))  # Asylum Demon body textures live in the shared c2239 pack
        tdesc = ", ".join(f"{k}:{im.size[0]}x{im.size[1]}" for k, (im, _) in list(tx.items())[:5]) + (" …" if len(tx) > 5 else "")
        L.append(f"| {c} | {s['meshes']} | {s['tris']} | {s['verts']} | {s['bones']} | {s['mats']} | {len(tx)}: {tdesc} |")

    L.append("\n## Player parts (Elite Knight set 9500 + Longsword 0201 + Knight Shield 1516)\n")
    L.append("| part | meshes | tris | verts | bones | materials | textures |\n|---|---|---|---|---|---|---|")
    ptot = 0
    for p in PARTS:
        b = Binder.from_path(DSR / "parts" / f"{p}.partsbnd.dcx")
        f = binder_flver(b)
        s = flver_stats(f)
        ptot += s["tris"]
        tx = binder_textures(b)
        tdesc = ", ".join(f"{k}:{im.size[0]}x{im.size[1]}" for k, (im, _) in list(tx.items())[:4]) + (" …" if len(tx) > 4 else "")
        L.append(f"| {p} | {s['meshes']} | {s['tris']} | {s['verts']} | {s['bones']} | {s['mats']} | {len(tx)}: {tdesc} |")
    L.append(f"| **knight total** | | **{ptot}** | | | | |")
    cooked = Path(args.cooked)
    if cooked.is_file():
        import json
        c = json.loads(cooked.read_text())
        L.append(f"\n## After cook v0 (`tools/cook_scene.py --scene {c['scene']}`, from `{cooked.name}`)\n")
        m = c["map"]
        L.append("| what | source tris | cooked tris | note |\n|---|---|---|---|")
        L.append(f"| map pieces {', '.join(m['pieces'])} | {m['src_tris']} | {m['simplified_tris']} | "
                 f"quadric simplify (pyfqmr) + split edges > 3 m, lightmap baked to vertex colour |")
        k = c["knight"]
        L.append(f"| Elite Knight (6 parts) | {k['src_tris']} | {k['tris']} | pose {k.get('pose')} |")
        d = c["demon"]
        L.append(f"| Asylum Demon c2230 | {d['src_tris']} | {d['tris']} | pose {d.get('pose')} |")
        f = c["file"]
        L.append(f"| **scene file** | | **{f['tris']}** | {f['bytes'] / 1024:.0f} KB, {f['batches']} batches, "
                 f"{f['verts']} verts (24 B), {f['tex']} textures = {f['tex_bytes'] / 1024:.0f} KB CLUT8 |")
        sizes = {}
        for t in c["textures"]:
            k2 = f"{t['src'][0]}x{t['src'][1]} -> {t['cooked'][0]}x{t['cooked'][1]}"
            sizes[k2] = sizes.get(k2, 0) + 1
        L.append("\n| texture source -> cooked (CLUT8, swizzled) | count |\n|---|---|")
        for k2, v in sorted(sizes.items(), key=lambda kv: -kv[1]):
            L.append(f"| {k2} | {v} |")
    L.append(f"\n_probe time {time.time() - t0:.1f} s_\n")

    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
