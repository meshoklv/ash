#!/usr/bin/env python3
"""src/perf/psp_cost.cfg -> perf_cost_gen.h (enum of keys + compiled-in defaults).

    tools/perf/cfg2h.py src/perf/psp_cost.cfg build/perf_cost_gen.h
The .cfg stays the single source of the coefficients; the header is a build artefact (not in git).
"""
import re
import sys


def parse(path):
    out = []
    for raw in open(path, encoding="utf-8"):
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        m = re.match(r"^([a-z0-9_]+)\s*=\s*([-+0-9.eE]+)$", line)
        if not m:
            raise SystemExit(f"{path}: bad line: {raw.rstrip()}")
        out.append((m.group(1), float(m.group(2))))
    return out


def main():
    src, dst = sys.argv[1], sys.argv[2]
    kv = parse(src)
    lines = ["/* generated by tools/perf/cfg2h.py from src/perf/psp_cost.cfg - do not edit */",
             "#ifndef PERF_COST_GEN_H", "#define PERF_COST_GEN_H", "enum {"]
    lines += [f"    PC_{k}," for k, _ in kv]
    lines += ["    PC__COUNT", "};", "static const char *const g_pc_names[PC__COUNT] = {"]
    lines += [f'    "{k}",' for k, _ in kv]
    lines += ["};", "static const float g_pc_defaults[PC__COUNT] = {"]
    lines += [f"    {v!r}f, /* {k} */" for k, v in kv]
    lines += ["};", "#endif", ""]
    open(dst, "w").write("\n".join(lines))


if __name__ == "__main__":
    main()
